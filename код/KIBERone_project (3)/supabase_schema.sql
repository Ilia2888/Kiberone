/* ============================================================================
   supabase_schema.sql — база данных приложения KIBERone-Учёт
   (Supabase / PostgreSQL 15 и выше)
   ----------------------------------------------------------------------------
   Схема полностью соответствует тому, что использует index5.html:
   таблицы tutors, groups, students, modules, module_students, attendance
   и вход через Supabase Auth (signInWithPassword по e-mail/паролю).

   ЧТО ИСПРАВЛЯЕТ И ДОБАВЛЯЕТ (в существующем проекте Supabase):
   1. Колонки groups.modules_plan и groups.is_camp. Без них приложение
      хранит план модулей и признак каникул ТОЛЬКО в браузере — именно об этом
      предупреждает жёлтая плашка «Добавьте в Supabase колонки...».
   2. UNIQUE-индекс attendance(group_id, student_id, date). Без него upsert
      табеля с onConflict 'group_id,student_id,date' не работает и отметки
      не синхронизируются между устройствами.
   3. Корректные внешние ключи с ON DELETE SET NULL / CASCADE — приложение
      сейчас делает «обнуление» ссылок вручную (UPDATE ... SET tutor_id=null
      и т.п.); теперь это гарантированно делает база.
   4. Индексы под реальные запросы приложения (по студенту, по группе).
   5. RLS: таблицы закрыты для анонимного ключа, все операции разрешены
      только вошедшим (TO authenticated). До этого данные читались
      анонимным ключом целиком.
   6. Триггер на attendance.updated_at — время правки теперь ставит база.
   7. (после тестов 2026-11) module_students в старых базах выравнивается до
      формы новой установки: добавляются id и created_at, уникальность пары
      (module_id, student_id) — иначе select(*) отдаёт разные формы строк
      на старой и новой базе.

   Формат modules_plan (jsonb, пишется приложением):
   [ { "moduleId": 3, "lessons": 24, "startDate": "2026-11-01",
       "endDate": "2026-12-15" }, ... ]

   Отметки attendance.value, которые ставит интерфейс:
   '+' — был, 'н' — не был, 'б' — болел, 'о' — опоздал, 'р' — перенос.

   ПОРЯДОК ЗАПУСКА: Supabase Dashboard -> SQL Editor -> вставить весь
   скрипт -> Run. Скрипт идемпотентен — повторный запуск безопасен.
   Пользователей для входа создавайте в Dashboard -> Authentication ->
   Users (таблицы auth.* трогать не нужно).
   ============================================================================ */

/* ============ 1. ТАБЛИЦЫ (для новой установки) ============ */

CREATE TABLE IF NOT EXISTS tutors (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      text NOT NULL,
    specialization text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS modules (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      text NOT NULL,
    hours      integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS groups (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL,
    level        smallint NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 4),
    day_of_week  text,                        -- «Понедельник» .. «Воскресенье»
    time_start   text,                        -- 'HH:MM'
    time_end     text,                        -- 'HH:MM'
    tutor_id     bigint REFERENCES tutors(id) ON DELETE SET NULL,
    module_id    bigint REFERENCES modules(id) ON DELETE SET NULL,  -- устаревшее поле, оставлено для совместимости
    modules_plan jsonb  NOT NULL DEFAULT '[]',-- план модулей группы
    is_camp      boolean NOT NULL DEFAULT false, -- признак каникул/лагеря
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS students (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   text NOT NULL,
    birth_date  date,                         -- возраст считается в приложении
    group_id    bigint REFERENCES groups(id) ON DELETE SET NULL,
    enrolled_at timestamptz NOT NULL DEFAULT now(),
    active      boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS module_students (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id  bigint NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    student_id bigint NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (module_id, student_id)
);

/* Табель: строка = (группа, ученик, дата). Составной PRIMARY KEY — ровно
   то, на что ссылается onConflict 'group_id,student_id,date' в приложении. */
CREATE TABLE IF NOT EXISTS attendance (
    group_id    bigint NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    student_id  bigint NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    date        date   NOT NULL,
    value       text   NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, student_id, date)
);

/* ============ 2. ДОРАБОТКА УЖЕ СУЩЕСТВУЮЩЕЙ БАЗЫ ============ */

/* 2.1. Группы: недостающие колонки (та самая плашка в интерфейсе) */
ALTER TABLE groups ADD COLUMN IF NOT EXISTS modules_plan jsonb  NOT NULL DEFAULT '[]';
ALTER TABLE groups ADD COLUMN IF NOT EXISTS is_camp     boolean NOT NULL DEFAULT false;
/* На случай более старой формы таблицы — остальные поля группы */
ALTER TABLE groups ADD COLUMN IF NOT EXISTS name        text;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS level       smallint NOT NULL DEFAULT 1;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS day_of_week  text;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS time_start   text;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS time_end     text;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS tutor_id     bigint;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS module_id    bigint;
ALTER TABLE groups ADD COLUMN IF NOT EXISTS created_at   timestamptz NOT NULL DEFAULT now();

/* 2.2. Остальные таблицы: страховка на старые формы.
   module_students: в старых базах таблица часто состоит только из пары
   (module_id, student_id) — выравниваем её до формы новой установки
   (id + created_at), чтобы select(*) везде отдавал одинаковую форму строк. */
ALTER TABLE module_students ADD COLUMN IF NOT EXISTS id         bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE module_students ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE tutors        ADD COLUMN IF NOT EXISTS full_name      text;
ALTER TABLE tutors        ADD COLUMN IF NOT EXISTS specialization text NOT NULL DEFAULT '';
ALTER TABLE modules       ADD COLUMN IF NOT EXISTS title text;
ALTER TABLE modules       ADD COLUMN IF NOT EXISTS hours integer NOT NULL DEFAULT 0;
ALTER TABLE students      ADD COLUMN IF NOT EXISTS full_name   text;
ALTER TABLE students      ADD COLUMN IF NOT EXISTS birth_date date;
ALTER TABLE students      ADD COLUMN IF NOT EXISTS group_id    bigint;
ALTER TABLE students      ADD COLUMN IF NOT EXISTS enrolled_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE students      ADD COLUMN IF NOT EXISTS active      boolean NOT NULL DEFAULT true;
ALTER TABLE attendance    ADD COLUMN IF NOT EXISTS date       date;
ALTER TABLE attendance    ADD COLUMN IF NOT EXISTS value      text;
ALTER TABLE attendance    ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

/* 2.3. Уникальный индекс табеля — без него upsert из приложения падает.
   Если в данных уже есть полные дубли (группа, ученик, дата) — сначала
   удалите их, индекс не создастся на дубликатах. */
CREATE UNIQUE INDEX IF NOT EXISTS uq_attendance_group_student_date
    ON attendance (group_id, student_id, date);

/* 2.4. Внешние ключи: ссылки чинит база, а не ручные UPDATE в коде.
   Каждый FK добавляется, только если его ещё нет и данные позволяют. */
DO $$
BEGIN
    BEGIN
        ALTER TABLE groups ADD CONSTRAINT fk_groups_tutor
            FOREIGN KEY (tutor_id) REFERENCES tutors(id) ON DELETE SET NULL;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_groups_tutor пропущен: %', SQLERRM;
    END;
    BEGIN
        ALTER TABLE groups ADD CONSTRAINT fk_groups_module
            FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE SET NULL;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_groups_module пропущен: %', SQLERRM;
    END;
    BEGIN
        ALTER TABLE students ADD CONSTRAINT fk_students_group
            FOREIGN KEY (group_id) REFERENCES groups(id) ON DELETE SET NULL;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_students_group пропущен: %', SQLERRM;
    END;
    BEGIN
        ALTER TABLE module_students ADD CONSTRAINT fk_module_students_module
            FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_module_students_module пропущен: %', SQLERRM;
    END;
    BEGIN
        ALTER TABLE module_students ADD CONSTRAINT fk_module_students_student
            FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_module_students_student пропущен: %', SQLERRM;
    END;
    BEGIN
        ALTER TABLE attendance ADD CONSTRAINT fk_attendance_group
            FOREIGN KEY (group_id) REFERENCES groups(id) ON DELETE CASCADE;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_attendance_group пропущен: %', SQLERRM;
    END;
    BEGIN
        ALTER TABLE attendance ADD CONSTRAINT fk_attendance_student
            FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'fk_attendance_student пропущен: %', SQLERRM;
    END;
    BEGIN
        /* Уникальность пары (модуль, ученик) в старой таблице — как в новой
           установке; при дублях в данных пропускается с уведомлением */
        ALTER TABLE module_students ADD CONSTRAINT uq_module_students_pair
            UNIQUE (module_id, student_id);
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'uq_module_students_pair пропущен: %', SQLERRM;
    END;
END $$;

/* 2.5. Индексы под запросы приложения (группы ученика, табель по ученику,
       группы преподавателя) */
CREATE INDEX IF NOT EXISTS idx_students_group_id        ON students (group_id);
CREATE INDEX IF NOT EXISTS idx_module_students_student  ON module_students (student_id);
CREATE INDEX IF NOT EXISTS idx_groups_tutor             ON groups (tutor_id);
CREATE INDEX IF NOT EXISTS idx_attendance_student      ON attendance (student_id);

/* ============ 3. updated_at ставит база ============ */

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_attendance_updated ON attendance;
CREATE TRIGGER trg_attendance_updated
    BEFORE UPDATE ON attendance
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

/* ============ 4. RLS: данные видны только вошедшим ============
   Приложение входит через Supabase Auth (signInWithPassword), после входа
   все запросы идут под ролью authenticated. Анонимный ключ читать и писать
   больше ничего не может. Пользователей для входа создавайте в
   Dashboard -> Authentication -> Users. */

ALTER TABLE tutors         ENABLE ROW LEVEL SECURITY;
ALTER TABLE groups          ENABLE ROW LEVEL SECURITY;
ALTER TABLE students        ENABLE ROW LEVEL SECURITY;
ALTER TABLE modules         ENABLE ROW LEVEL SECURITY;
ALTER TABLE module_students ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance      ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['tutors','groups','students','modules','module_students','attendance']
    LOOP
        /* SELECT */
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', t || '_sel', t);
        EXECUTE format('CREATE POLICY %I ON %I FOR SELECT TO authenticated USING (true)',
                       t || '_sel', t);
        /* INSERT (нужно и для upsert табеля вместе с UPDATE) */
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', t || '_ins', t);
        EXECUTE format('CREATE POLICY %I ON %I FOR INSERT TO authenticated WITH CHECK (true)',
                       t || '_ins', t);
        /* UPDATE (вторая половина upsert) */
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', t || '_upd', t);
        EXECUTE format('CREATE POLICY %I ON %I FOR UPDATE TO authenticated USING (true) WITH CHECK (true)',
                       t || '_upd', t);
        /* DELETE (удаление учеников/групп/модулей, очистка отметок) */
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', t || '_del', t);
        EXECUTE format('CREATE POLICY %I ON %I FOR DELETE TO authenticated USING (true)',
                       t || '_del', t);
    END LOOP;
END $$;

/* ============ 5. ПРОВЕРКА ПОСЛЕ ЗАПУСКА ============ */

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('tutors','groups','students','modules','module_students','attendance')
ORDER BY table_name;

SELECT column_name, data_type
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'groups'
ORDER BY ordinal_position;

SELECT c.relname AS таблица, c.relrowsecurity AS rls_включён
FROM pg_class c
WHERE c.relnamespace = 'public'::regnamespace
  AND c.relname IN ('tutors','groups','students','modules','module_students','attendance')
ORDER BY c.relname;

SELECT indexname
FROM pg_indexes
WHERE schemaname = 'public'
  AND indexname IN ('uq_attendance_group_student_date','idx_students_group_id',
                    'idx_module_students_student','idx_groups_tutor','idx_attendance_student')
ORDER BY indexname;
